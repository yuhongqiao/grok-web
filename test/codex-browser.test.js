import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import express from "express";
import { createBrowserLab } from "../server/codex-browser.js";
import { tempRoot, listen } from "./helpers.js";
import { waitFor } from "./codex-helpers.js";

const chrome = [process.env.CHROME_BIN, "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", "/usr/bin/google-chrome", "/usr/bin/chromium"].find((file) => file && fs.existsSync(file));

test("browser login profiles, manual takeover, recording, replay, diagnostics and visual baselines", { skip: !chrome, timeout: 60_000 }, async () => {
  const root = tempRoot();
  const app = express(); app.use(express.urlencoded({ extended: false }));
  let changed = false;
  app.get("/", (req, res) => res.send(req.headers.cookie?.includes("loggedin=yes") ? `<body style="background:${changed ? "pink" : "white"}"><h1>Dashboard</h1><a id="logout" href="/logout">Logout</a><script>console.error('synthetic console diagnostic');fetch('/missing')</script></body>` : '<form action="/login" method="post"><label>User<input id="username" name="username"></label><label>Password<input id="password" name="password" type="password"></label><button id="login">Login</button></form>'));
  app.post("/login", (_req, res) => { res.cookie("loggedin", "yes", { maxAge: 60_000 }); res.redirect("/"); });
  app.get("/logout", (_req, res) => { res.clearCookie("loggedin"); res.redirect("/"); });
  app.get("/missing", (_req, res) => res.sendStatus(503));
  const { server, port } = await listen(app);
  const url = `http://127.0.0.1:${port}`;
  const lab = createBrowserLab({ dataDir: path.join(root, "browser"), headless: true, executablePath: chrome });
  const profile = "isolated login";
  try {
    let state = await lab.open(root, profile, url);
    assert.equal(state.elements.some((entry) => entry.type === "password"), true);
    await lab.recording(root, profile, "start");
    await lab.action(root, profile, { action: "fill", selector: "#username", text: "test-user" });
    await lab.action(root, profile, { action: "fill", selector: "#password", text: "never-save-this-password" });
    await lab.action(root, profile, { action: "click", selector: "#login" });
    state = await lab.action(root, profile, { action: "assert", text: "Dashboard" });
    assert.equal(Boolean(state.image), true);
    await lab.action(root, profile, { action: "click", selector: "#logout" });
    await lab.action(root, profile, { action: "assert", selector: "#password" });
    const entry = await lab.recording(root, profile, "save", "Login and logout");
    assert.equal(JSON.stringify(entry).includes("never-save-this-password"), false);
    assert.equal(entry.steps.find((step) => step.secret).text, "{{secret_1}}");
    await assert.rejects(lab.run(root, profile, entry.id), /secret_1/);
    const report = await lab.run(root, profile, entry.id, { secret_1: "runtime-only-secret" });
    assert.equal(report.status, "passed", JSON.stringify(report));
    assert.equal(JSON.stringify(report).includes("runtime-only-secret"), false);
    assert.equal(report.console.some((entry) => entry.text.includes("synthetic console diagnostic")), true);
    assert.equal(report.network.some((entry) => entry.status === 503), true);
    assert.equal(lab.artifact(root, profile, report.id, "0.png").mime, "image/png");
    lab.baseline(root, profile, report.id);
    const comparison = await lab.run(root, profile, entry.id, { secret_1: "runtime-only-secret" });
    assert.equal(comparison.visual.sameSize, true);
    assert.equal(comparison.visual.percent, 0);
    await lab.manual(root, profile, true);
    await assert.rejects(lab.action(root, profile, { action: "reload" }), /接管/);
    await lab.manual(root, profile, false);
    await lab.action(root, profile, { action: "fill", selector: "#password", text: "persistence-test" });
    await lab.action(root, profile, { action: "click", selector: "#login" });
    await lab.action(root, profile, { action: "assert", text: "Dashboard" });
    await lab.close(root, profile);
    state = await lab.open(root, profile, url);
    assert.match(state.text, /Dashboard/);
    const other = await lab.open(root, "another profile", url);
    assert.equal(other.elements.some((entry) => entry.type === "password"), true);
    await lab.recording(root, profile, "start");
    await lab.action(root, profile, { action: "assert", text: "Dashboard" });
    const dashboard = await lab.recording(root, profile, "save", "Dashboard assertion");
    const first = await lab.run(root, profile, dashboard.id); lab.baseline(root, profile, first.id);
    changed = true;
    const visual = await lab.run(root, profile, dashboard.id);
    assert.ok(visual.visual.percent > 20);
    await lab.action(root, profile, { action: "click", selector: "#logout" });
    const failed = await lab.run(root, profile, dashboard.id);
    assert.equal(failed.status, "failed"); assert.ok(failed.steps.at(-1).error); assert.ok(failed.steps.at(-1).screenshot);
    state = await lab.action(root, profile, { action: "viewport", width: 390, height: 844 });
    assert.equal(state.viewport.width, 390);
    const screenshot = await lab.tool("browser_screenshot", { projectPath: root, profile });
    assert.equal(screenshot.content[0].type, "image");
    await assert.rejects(lab.open(root, profile, "file:///etc/passwd"), /HTTP/);
    assert.throws(() => lab.artifact(root, profile, "../../escape", "report.json"), /路径/);
    console.log(`Browser reports: ${root}/browser`);
  } finally { await lab.stop(); await new Promise((resolve) => server.close(resolve)); }
});

test("embedded browser hands login to the user, blocks automation and resumes the waiting native tool", { skip: !chrome, timeout: 30_000 }, async () => {
  const root = tempRoot();
  const app = express();
  app.get("/", (_req, res) => res.send('<label>Password<input id="password" type="password"></label><button id="login" onclick="document.body.innerHTML=\'<h1>Verified login</h1>\'">Login</button>'));
  const { server, port } = await listen(app);
  const lab = createBrowserLab({ dataDir: path.join(root, "browser"), executablePath: chrome });
  let pending;
  try {
    await lab.tool("browser_open", { projectPath: root, url: `http://127.0.0.1:${port}` });
    await assert.rejects(lab.interact(root, "default", { action: "click", selector: "#login" }), /先接管/);
    pending = lab.tool("browser_handoff", { projectPath: root, reason: "请在页面中输入登录口令" });
    await waitFor(async () => (await lab.state(root, "default", false)).handoffReason);
    await assert.rejects(lab.tool("browser_handoff", { projectPath: root, reason: "重复接管" }), /正在等待/);
    await assert.rejects(lab.tool("browser_action", { projectPath: root, action: "click", selector: "#login" }), /接管/);
    await lab.interact(root, "default", { action: "click", selector: "#password" });
    let state = await lab.interact(root, "default", { action: "type", text: "private-login-password" });
    assert.equal(JSON.stringify(state).includes("private-login-password"), false);
    await assert.rejects(lab.interact(root, "default", { action: "navigate", url: "https://example.com" }), /接管操作/);
    await lab.interact(root, "default", { action: "click", selector: "#login" });
    await lab.manual(root, "default", false);
    const resumed = JSON.parse((await pending).content[0].text);
    assert.match(resumed.text, /Verified login/);
    assert.equal(resumed.manual, false);
    state = JSON.parse((await lab.tool("browser_action", { projectPath: root, action: "assert", text: "Verified login" })).content[0].text);
    assert.equal(state.opened, true);
    const closing = lab.tool("browser_handoff", { projectPath: root, reason: "取消验证" });
    const rejected = assert.rejects(closing, /关闭/);
    await waitFor(async () => (await lab.state(root, "default", false)).handoffReason === "取消验证");
    await lab.close(root, "default");
    await rejected;
  } finally { await lab.stop(); await pending?.catch(() => {}); await new Promise((resolve) => server.close(resolve)); }
});
