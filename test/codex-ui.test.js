test("Codex discards stale search pages after changing the query in the sidebar and archives", { skip: !chrome, timeout: 45_000 }, async () => {
  const f = await codexFixture();
  const browser = await puppeteer.launch({ executablePath: chrome, headless: true, args: ["--no-sandbox", "--disable-dev-shm-usage"] });
  try {
    f.codex.addProject(f.cwd);
    const page = await browser.newPage();
    await page.setViewport({ width: 1280, height: 850 });
    await page.goto(`${f.base}/codex`);
    await waitText(page, "本地 Codex 已连接");
    let held;
    await page.setRequestInterception(true);
    page.on("request", (request) => {
      const url = new URL(request.url());
      if (url.pathname !== "/api/codex/threads" || !["alpha", "beta"].includes(url.searchParams.get("q"))) return request.continue();
      if (url.searchParams.get("cursor") === "held") { held = request; return; }
      const query = url.searchParams.get("q");
      const next = url.searchParams.get("cursor") === "next";
      request.respond({ status: 200, contentType: "application/json", body: JSON.stringify({ threads: [{ id: `${query}-${next ? "next" : "first"}`, name: `${query} ${next ? "next" : "first"}`, cwd: f.cwd, updatedAt: Date.now() / 1000 }], nextCursor: next ? null : query === "alpha" ? "held" : "next" }) });
    });
    for (const archived of [false, true]) {
      if (archived) await page.click("button[aria-label='已归档的 Codex 会话']");
      const input = archived ? "input[aria-label='搜索已归档会话']" : "input[aria-label='搜索 Codex 会话']";
      const list = archived ? ".pick-list" : ".side-scroll";
      const more = archived ? ".modal .btn" : ".session-more";
      await page.type(input, "alpha");
      await page.waitForFunction((selector) => document.querySelector(selector)?.innerText.includes("alpha first"), {}, list);
      await page.click(more);
      await waitFor(() => held);
      await page.click(input, { clickCount: 3 });
      await page.type(input, "beta");
      await page.waitForFunction((selector) => document.querySelector(selector)?.innerText.includes("beta first"), {}, list);
      const oldPage = held;
      const received = page.waitForResponse((response) => response.url() === oldPage.url());
      await oldPage.respond({ status: 200, contentType: "application/json", body: JSON.stringify({ threads: [{ id: "alpha-stale", name: "alpha stale", cwd: f.cwd, updatedAt: Date.now() / 1000 }], nextCursor: null }) });
      await received;
      await page.evaluate(() => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))));
      assert.equal(await page.$eval(list, (element) => element.innerText.includes("alpha stale")), false);
      assert.equal(await page.$eval(more, (element) => element.disabled), false);
      await page.click(more);
      await page.waitForFunction((selector) => document.querySelector(selector)?.innerText.includes("beta next"), {}, list);
      held = null;
    }
  } finally { await browser.close(); await f.close(); }
});

